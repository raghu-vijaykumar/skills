"""Rebuild small synthetic capability evidence without private footage."""

from __future__ import annotations

import json
import subprocess
import tempfile
from pathlib import Path

from PIL import Image, ImageDraw

from test_fastpan import FastPanTests, fastpan, model


HERE = Path(__file__).resolve().parents[1] / "previews"


def frames(video: Path, seconds: int = 4) -> list[Image.Image]:
    result = subprocess.run(
        ["ffmpeg", "-hide_banner", "-loglevel", "error", "-i", str(video),
         "-t", str(seconds), "-vf", "fps=2,scale=160:90", "-f", "rawvideo",
         "-pix_fmt", "rgb24", "pipe:1"], capture_output=True, check=True)
    size = 160 * 90 * 3
    return [Image.frombytes("RGB", (160, 90), result.stdout[index:index + size])
            for index in range(0, len(result.stdout), size) if len(result.stdout[index:index + size]) == size]


def main() -> None:
    HERE.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory() as temp:
        fixture = FastPanTests("test_scan_finds_sustained_pan_but_not_isolated_scene_cut")
        source = Path(temp) / "synthetic-pan.mp4"
        fixture._make_video(source)
        report = Path(temp) / "scan.json"
        fastpan.scan(source, report)
        report_data = json.loads(report.read_text())
        # The private, temporary build path is deliberately removed from committed evidence.
        report_data["source"] = "<synthetic source generated by tests/build_evidence.py>"
        (HERE / "scan-report.json").write_text(json.dumps(report_data, indent=2) + "\n", encoding="utf-8")

        stat = source.stat()
        decisions = Path(temp) / "decisions.json"
        decisions.write_text(json.dumps({
            "schema": fastpan.DECISION_SCHEMA, "source": str(source),
            "source_sha256": fastpan.sha256_file(source), "source_bytes": stat.st_size,
            "source_mtime_ns": stat.st_mtime_ns, "fps": 30, "actor": "human",
            "reviewer": "synthetic fixture", "review_note": "Known generated sweep only",
            "cuts": [{"id": "pan-0001", "start_frame": 60, "end_frame": 120,
                      "review_status": "approved"}]}, indent=2), encoding="utf-8")
        preview = Path(temp) / "preview.mp4"
        fastpan.preview(source, decisions, "pan-0001", preview)

        plan = Path(temp) / "plan.json"
        plan.write_text(json.dumps({"schema_version": 1, "kind": "edited",
                                    "stage": "edited-render", "goal": "synthetic evidence",
                                    "steps": [{"id": "S01"}]}), encoding="utf-8")
        digest = fastpan.sha256_file(plan)
        plan.with_name("approval.json").write_text(json.dumps({
            "plan_sha256": digest, "review_note": "synthetic fixture"}), encoding="utf-8")
        plan.with_name("checklist.json").write_text(json.dumps({
            "plan_sha256": digest, "items": [{"id": "S01"}]}), encoding="utf-8")
        timeline = model.make_initial(plan, source, Path(temp) / "final.mp4",
                                      fps=30, width=320, height=180)
        timeline_path = Path(temp) / "timeline.json"
        timeline_path.write_text(json.dumps(timeline), encoding="utf-8")
        changes = Path(temp) / "changes.json"
        fastpan.timeline_changes(source, decisions, timeline_path, changes)
        (HERE / "changes.json").write_text(changes.read_text(), encoding="utf-8")

        original_frames = frames(source)
        cut_frames = frames(preview)
        panels = []
        for original, cut in zip(original_frames, cut_frames):
            panel = Image.new("RGB", (320, 110), "#111111")
            panel.paste(original, (0, 20))
            panel.paste(cut, (160, 20))
            draw = ImageDraw.Draw(panel)
            draw.text((4, 4), "Original", fill="white")
            draw.text((164, 4), "Pan removed", fill="white")
            panels.append(panel.convert("P", palette=Image.Palette.ADAPTIVE, colors=96))
        panels[0].save(HERE / "fastpan-cut.gif", save_all=True,
                       append_images=panels[1:], duration=500, loop=0, optimize=True)
        print(f"evidence: {len(report_data['candidates'])} candidates, {len(panels)} GIF frames, 1 cut")


if __name__ == "__main__":
    main()
